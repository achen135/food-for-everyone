/**
 * Copy MapLibre's web worker into `public/maplibre/` so we can serve it from a
 * stable, same-origin URL.
 *
 * Why this exists
 * ---------------
 * maplibre-gl's ESM build works out where its worker lives by resolving
 * `./maplibre-gl-worker.mjs` against `import.meta.url`:
 *
 *   function getWorkerUrl() {
 *     let url = import.meta.url;
 *     ...
 *     return new URL(`./${workerFile}`, url).href;
 *   }
 *
 * That assumes the package's dist files are served next to each other. Under a
 * bundler they are not: `import.meta.url` is the *bundled chunk*
 * (`/_next/static/chunks/<hash>.js`), so maplibre asks for
 * `/_next/static/chunks/maplibre-gl-worker.mjs`, which doesn't exist. Next
 * answers with its 404 page, and the browser refuses it:
 *
 *   Failed to load module script: The server responded with a non-JavaScript
 *   MIME type of "text/html".
 *
 * The map then renders blank with no thrown error, because the failure is
 * inside worker startup.
 *
 * The fix is `setWorkerUrl()` (see components/map/counterparty-map.tsx) pointed
 * at a copy we serve ourselves. `maplibre-gl-worker.mjs` imports
 * `./maplibre-gl-shared.mjs`, so both files have to land in the same directory.
 *
 * Copied at build time rather than committed so the worker can never drift out
 * of sync with the installed maplibre-gl version. Runs from `predev` and
 * `prebuild`; `public/maplibre/` is gitignored.
 */

import { createRequire } from "node:module";
import { copyFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const WORKER_FILES = ["maplibre-gl-worker.mjs", "maplibre-gl-shared.mjs"];

const require = createRequire(import.meta.url);
const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const pkgPath = require.resolve("maplibre-gl/package.json");
const { version } = require("maplibre-gl/package.json");
const distDir = join(dirname(pkgPath), "dist");
const outDir = join(projectRoot, "public", "maplibre");

await mkdir(outDir, { recursive: true });

for (const file of WORKER_FILES) {
  await copyFile(join(distDir, file), join(outDir, file));
}

// Leaves a breadcrumb for anyone who finds these files and wonders why.
await writeFile(
  join(outDir, "README.txt"),
  `Generated by scripts/copy-maplibre-worker.mjs — do not edit, do not commit.\n` +
    `Copied from maplibre-gl@${version}.\n` +
    `Served at /maplibre/* and wired up via setWorkerUrl() in\n` +
    `components/map/counterparty-map.tsx. See that script's header for why.\n`,
);

console.log(
  `[maplibre] worker copied to public/maplibre/ (maplibre-gl@${version})`,
);
